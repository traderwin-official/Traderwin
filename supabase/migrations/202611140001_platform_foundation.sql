-- Young Tiger FX platform foundation (idempotent table creation).
-- Review existing schema before applying. No existing table or user data is dropped.
-- Internal execution/payment records are service-role managed; members receive read-only access to their own records.

create table if not exists public.market_instruments (
  id bigint generated by default as identity primary key,
  symbol text not null unique,
  display_name text not null,
  market_category text not null,
  provider text,
  is_active boolean not null default false,
  data_status text not null default 'UNVERIFIED' check (data_status in ('UNVERIFIED','LIVE','DELAYED','OFFLINE')),
  updated_at timestamptz not null default now()
);

create table if not exists public.ai_trade_ideas (
  id uuid primary key default gen_random_uuid(),
  instrument text not null,
  market_category text not null,
  direction text not null check (direction in ('BUY','SELL','UP','DOWN','NEUTRAL')),
  timeframe text,
  entry_low numeric,
  entry_high numeric,
  stop_loss numeric,
  take_profit jsonb not null default '[]'::jsonb,
  rationale text not null,
  risk_reward numeric,
  source_refs jsonb not null default '[]'::jsonb,
  data_timestamp timestamptz,
  model_version text,
  status text not null default 'DRAFT' check (status in ('DRAFT','ACTIVE','EXPIRED','INVALIDATED')),
  created_at timestamptz not null default now(),
  expires_at timestamptz
);

create table if not exists public.bot_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  bot_key text,
  event_type text not null,
  account_mode text not null default 'DEMO' check (account_mode in ('DEMO','REAL')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.demo_bot_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  broker text not null,
  broker_account_ref text,
  instrument text not null,
  strategy text,
  status text not null default 'STOPPED' check (status in ('STOPPED','RUNNING','PAUSED','ERROR')),
  risk_per_trade_pct numeric(5,2) not null default 0.5 check (risk_per_trade_pct > 0 and risk_per_trade_pct <= 2),
  max_daily_loss_pct numeric(5,2) not null default 2 check (max_daily_loss_pct > 0 and max_daily_loss_pct <= 10),
  started_at timestamptz,
  stopped_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.demo_bot_trades (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.demo_bot_sessions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  instrument text not null,
  side text not null check (side in ('BUY','SELL','UP','DOWN')),
  quantity numeric not null check (quantity > 0),
  entry_price numeric,
  exit_price numeric,
  stop_loss numeric,
  take_profit numeric,
  pnl numeric not null default 0,
  status text not null default 'PENDING' check (status in ('PENDING','OPEN','CLOSED','CANCELLED','REJECTED')),
  opened_at timestamptz,
  closed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.bot_mode_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  broker text not null,
  instrument text not null,
  account_mode text not null default 'DEMO' check (account_mode in ('DEMO','REAL')),
  timeframe text,
  strategy text,
  risk_per_trade numeric(5,2) not null default 0.5 check (risk_per_trade > 0 and risk_per_trade <= 2),
  max_daily_loss numeric(5,2) not null default 2 check (max_daily_loss > 0 and max_daily_loss <= 10),
  max_open_positions integer not null default 1 check (max_open_positions between 1 and 10),
  enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, broker, instrument, account_mode)
);

create table if not exists public.real_execution_authorizations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  broker text not null,
  broker_account_ref text not null,
  scopes jsonb not null default '[]'::jsonb,
  risk_acknowledged_at timestamptz,
  approved_by uuid references auth.users(id),
  approval_status text not null default 'PENDING' check (approval_status in ('PENDING','APPROVED','REVOKED','REJECTED')),
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);

create table if not exists public.portfolio_profit_protection_state (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  broker text not null,
  broker_account_ref text not null,
  account_mode text not null check (account_mode in ('DEMO','REAL')),
  peak_unrealized_profit_usd numeric not null default 0,
  protection_active boolean not null default false,
  monitor_manual_trades boolean not null default false,
  updated_at timestamptz not null default now(),
  unique(user_id, broker, broker_account_ref, account_mode)
);

create table if not exists public.bot_products (
  id uuid primary key default gen_random_uuid(),
  product_code text not null unique,
  name text not null,
  description text,
  price numeric(12,2) not null check (price >= 0),
  currency text not null default 'KES',
  billing_period text not null default 'monthly' check (billing_period in ('monthly','lifetime','one_time')),
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.payment_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  service_code text not null,
  amount numeric(12,2) not null check (amount > 0),
  currency text not null default 'KES',
  payment_method text not null default 'MPESA',
  phone_number text,
  provider_checkout_id text unique,
  provider_receipt text unique,
  status text not null default 'PENDING' check (status in ('PENDING','PROCESSING','PAID','FAILED','CANCELLED','REFUNDED')),
  provider_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create table if not exists public.user_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  service_code text not null,
  status text not null default 'PENDING' check (status in ('PENDING','ACTIVE','PAST_DUE','CANCELLED','EXPIRED')),
  amount numeric(12,2) not null,
  currency text not null default 'USD',
  starts_at timestamptz,
  ends_at timestamptz,
  payment_order_id uuid references public.payment_orders(id),
  created_at timestamptz not null default now()
);

create table if not exists public.course_enrolments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  course_code text not null,
  status text not null default 'PENDING' check (status in ('PENDING','ACTIVE','COMPLETED','CANCELLED')),
  payment_order_id uuid references public.payment_orders(id),
  enrolled_at timestamptz not null default now(),
  unique(user_id, course_code)
);

create table if not exists public.bot_license_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.bot_products(id),
  payment_order_id uuid references public.payment_orders(id),
  status text not null default 'PENDING' check (status in ('PENDING','PAID','FULFILLED','CANCELLED','REFUNDED')),
  created_at timestamptz not null default now()
);

create table if not exists public.bot_licenses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.bot_products(id),
  order_id uuid references public.bot_license_orders(id),
  license_key_hash text not null unique,
  status text not null default 'PENDING' check (status in ('PENDING','ACTIVE','REVOKED','EXPIRED')),
  activated_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.bot_license_delivery_outbox (
  id uuid primary key default gen_random_uuid(),
  license_id uuid not null references public.bot_licenses(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  delivery_channel text not null default 'IN_APP',
  status text not null default 'PENDING' check (status in ('PENDING','SENT','FAILED')),
  attempts integer not null default 0,
  last_error text,
  created_at timestamptz not null default now(),
  delivered_at timestamptz
);

create index if not exists bot_activity_user_created_idx on public.bot_activity(user_id, created_at desc);
create index if not exists demo_bot_sessions_user_idx on public.demo_bot_sessions(user_id, created_at desc);
create index if not exists demo_bot_trades_user_created_idx on public.demo_bot_trades(user_id, created_at desc);
create index if not exists ai_trade_ideas_status_created_idx on public.ai_trade_ideas(status, created_at desc);
create index if not exists payment_orders_user_created_idx on public.payment_orders(user_id, created_at desc);
create index if not exists user_subscriptions_user_status_idx on public.user_subscriptions(user_id, status);
create index if not exists course_enrolments_user_idx on public.course_enrolments(user_id);
create index if not exists bot_license_orders_user_idx on public.bot_license_orders(user_id, created_at desc);

